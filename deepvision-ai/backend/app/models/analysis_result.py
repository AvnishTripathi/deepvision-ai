"""
DeepVision AI — Analysis Result Entity Model
Stores structured numerical metrics, bounding box coordinates, landmark keypoints,
and processing telemetry resulting from computer vision evaluations.
CRITICAL MANDATE:
Does NOT store identity names, biometric profiles, vector embeddings, or raw face images.
"""

from typing import Optional
from sqlalchemy import String, Integer, Float, DateTime, ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, UUIDPrimaryKeyMixin


class AnalysisResult(Base, UUIDPrimaryKeyMixin):
    """Structured analytical output generated by vision pipeline inference."""

    __tablename__ = "analysis_results"

    job_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("analysis_jobs.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    model_version_id: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("model_versions.id", ondelete="SET NULL"),
        nullable=True,
    )
    face_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
    )
    results_json: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    metrics_json: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    processing_time_ms: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
    )
    created_at: Mapped[DateTime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    job = relationship("AnalysisJob", foreign_keys=[job_id], lazy="selectin")
    model_version = relationship("ModelVersion", foreign_keys=[model_version_id], lazy="selectin")

